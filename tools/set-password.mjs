// Set the crew password for web co-op. Only a salted PBKDF2 hash is written
// into the game, so the password itself never ships in the code.
//   node tools/set-password.mjs "your-password"   (or omit to generate one)
import { pbkdf2Sync, randomBytes, randomInt } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const words1 = ['briny', 'salty', 'rusty', 'gusty', 'soggy', 'jolly', 'foggy', 'sandy'];
const words2 = ['pelican', 'tugboat', 'barnacle', 'flatbed', 'anchor', 'lighthouse', 'oyster', 'harbor'];
const pw = (process.argv[2] || `${words1[randomInt(words1.length)]}-${words2[randomInt(words2.length)]}-${randomInt(1000, 10000)}`).trim();
const salt = 'wide-load:' + randomBytes(8).toString('hex');
const iterations = 150000;
const hash = pbkdf2Sync(pw, salt, iterations, 32, 'sha256').toString('hex');
writeFileSync(new URL('../src/net/crewkey.js', import.meta.url), `// Crew password check for web co-op. Generated by tools/set-password.mjs;
// only the salted PBKDF2-SHA256 hash is stored here, never the password.
export const CREW_KEY = { salt: '${salt}', iterations: ${iterations}, hash: '${hash}' };
`);
console.log('Crew password set to:', pw);
